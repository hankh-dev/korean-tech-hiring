from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

from .aggregate import build_history, build_reports, build_stats
from .config import DEFAULT_OUT_DIR, HISTORY_DIR, ROOT, load_boards, load_notes
from .normalize import dedupe_jobs, normalize_job, sort_jobs
from .sources import fetch_all
from .stacks import STACKS
from .text import today_kst


def write_json(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    os.replace(tmp, path)


def load_previous(path: Path) -> dict | None:
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None


def prune_history(days: int = 400) -> None:
    if not HISTORY_DIR.exists():
        return
    cutoff = today_kst() - timedelta(days=days)
    for path in HISTORY_DIR.glob("*.json"):
        try:
            day = date.fromisoformat(path.stem)
        except ValueError:
            continue
        if day < cutoff:
            path.unlink()


def write_stack_names() -> None:
    """Keep the web stack-name dictionary in sync with the pipeline dictionary."""
    path = ROOT / "web" / "lib" / "stack-names.ts"
    if not path.parent.exists():
        return
    lines = [
        "// Auto-generated by pipeline/joblab/build.py. Do not edit.",
        "export const STACK_NAMES: Record<string, string> = {",
    ]
    for stack in STACKS:
        lines.append(f"  {json.dumps(stack.slug)}: {json.dumps(stack.name, ensure_ascii=False)},")
    lines.append("};")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build JobLab static data")
    parser.add_argument("--out", default=str(DEFAULT_OUT_DIR), help="output directory")
    parser.add_argument("--offline", action="store_true", help="rebuild from existing jobs.json")
    parser.add_argument("--force", action="store_true", help="ignore the job-count safety guard")
    parser.add_argument("--only", default="", help="comma separated board slugs")
    parser.add_argument("--no-history", action="store_true", help="do not write a history snapshot")
    args = parser.parse_args(argv)

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    previous = load_previous(out_dir / "jobs.json")
    previous_jobs = previous.get("jobs", []) if previous else []
    previous_all = previous.get("allKoreaJobs", len(previous_jobs)) if previous else 0

    boards = load_boards()
    notes = load_notes()
    generated_at = datetime.now(tz=timezone.utc).isoformat(timespec="seconds")

    if args.offline:
        if not previous_jobs:
            print("No previous jobs.json to rebuild from.", file=sys.stderr)
            return 2
        jobs = [{**job, "isTech": True, "source": job.get("source", "offline")} for job in previous_jobs]
        all_korea_jobs = previous_all
        errors: list[dict] = []
        print(f"Offline mode: rebuilding from {len(jobs)} published jobs")
    else:
        only = {slug.strip() for slug in args.only.split(",") if slug.strip()} or None
        print(f"Fetching {len(boards)} boards...")
        raw_jobs, errors = fetch_all(boards, only=only)
        all_korea_jobs = len(raw_jobs)
        jobs = dedupe_jobs([normalize_job(raw) for raw in raw_jobs])
        tech_jobs_now = [job for job in jobs if job["isTech"]]
        print(f"Fetched {all_korea_jobs} Korea jobs, {len(tech_jobs_now)} tech roles")

        if previous_jobs and not args.force:
            ratio = len(tech_jobs_now) / len(previous_jobs) if previous_jobs else 1
            if ratio < 0.5:
                print(
                    f"Safety guard: tech jobs dropped from {len(previous_jobs)} to "
                    f"{len(tech_jobs_now)} ({ratio:.0%}). Re-run with --force to accept.",
                    file=sys.stderr,
                )
                return 3

    tech_jobs = sort_jobs([job for job in jobs if job["isTech"]])
    if not tech_jobs:
        print("No tech jobs found. Keeping existing data.", file=sys.stderr)
        return 4

    stats = build_stats(tech_jobs, boards, errors, all_korea_jobs, generated_at)
    reports = build_reports(tech_jobs, notes, weeks=8)

    published_jobs = [
        {key: value for key, value in job.items() if key not in {"isTech", "source"}}
        for job in tech_jobs
    ]

    write_json(
        out_dir / "jobs.json",
        {
            "generatedAt": generated_at,
            "allKoreaJobs": all_korea_jobs,
            "techJobs": len(published_jobs),
            "jobs": published_jobs,
        },
    )
    write_json(out_dir / "stats.json", stats)
    write_json(
        out_dir / "reports.json",
        {"generatedAt": generated_at, "reports": reports},
    )
    write_stack_names()

    if not args.no_history:
        HISTORY_DIR.mkdir(parents=True, exist_ok=True)
        write_json(HISTORY_DIR / f"{today_kst().isoformat()}.json", build_history(stats))
        prune_history()

    totals = stats["totals"]
    print()
    print(f"개발 직군 {totals['techJobs']}건 / 전체 한국 공고 {totals['allKoreaJobs']}건")
    print(f"기업 {totals['companies']}곳 / AI 관련 {totals['aiJobs']}건 / 신규 7일 {totals['new7d']}건")
    print("스택 Top 10:")
    for row in stats["stacks"][:10]:
        print(f"  {row['name']:<16} {row['count']:>3}건 ({row['share']}%)")
    if errors:
        print(f"수집 실패 {len(errors)}건: {', '.join(error['board'] for error in errors)}")
    print(f"출력: {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
